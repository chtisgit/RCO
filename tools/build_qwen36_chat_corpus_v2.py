#!/usr/bin/env python3
"""Phase 4b of RCO_PLAN_NEW.md: build chat corpus v2, with on-policy replies.

Every sequence is a conversation rendered with the model's own chat
template; only the final assistant turn is scored.  The contexts come from
licensed sources (see ``SOURCES``) and from calibration v2's documents; the
scored replies are generated by the reference model itself (a Q6_K GGUF
quantized from the pinned BF16 checkpoint) with the model card's sampling.

Subcommands:

``prompts``
    Deterministic selection of the contexts: strata, languages, thinking
    on/off and the ``calibration``/``heldout`` split.  No source item of chat
    corpus v1 is reused.  Writes ``prompts.jsonl``.
``generate``
    Starts ``llama-server --jinja`` on the reference GGUF.  Per prompt:
    ``/apply-template`` renders the generation prompt, ``/tokenize`` (special
    tokens parsed) gives its tokens, and ``/completion`` samples the reply
    from exactly those tokens, returning the generated token ids (the
    end-of-generation token included).  Resumable; appends to
    ``generations.jsonl``.
``finalize``
    Tokens are prompt plus generated tokens; the scored targets are the
    generated ones.  Writes ``corpus.jsonl``, ``tokens.json`` and the
    manifest, in the format ``audit_qwen36_chat_kl.py`` reads.
"""

